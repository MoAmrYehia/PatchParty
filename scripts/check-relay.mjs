import assert from 'node:assert/strict';
import { createWorld } from '../lib/game.ts';
const origin = process.argv[2];
if (!origin) throw new Error('Usage: node scripts/check-relay.mjs <preview-origin>');
const response = await fetch(`${origin}/api/rooms`, { method: 'POST' });
assert.equal(response.status, 201, 'create room');
const { id, hostKey, readKey } = await response.json();
const snapshot = createWorld();
const write = key => fetch(`${origin}/api/rooms/${id}`, { method: 'PUT', headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' }, body: JSON.stringify(snapshot) });
assert.equal((await write(readKey)).status, 403, 'read key cannot write');
assert.equal((await write('invalid')).status, 403, 'invalid host key rejected');
assert.equal((await write(hostKey)).status, 200, 'host writes snapshot');
const read = await fetch(`${origin}/api/rooms/${id}`, { headers: { Authorization: `Bearer ${readKey}` } });
assert.equal(read.status, 200); assert.equal((await read.json()).snapshot.phase, 'ready');
assert.equal((await fetch(`${origin}/api/rooms/${id}`)).status, 404, 'missing reader token rejected');
assert.equal((await fetch(`${origin}/api/rooms/${id}`, { headers: { Authorization: `Bearer ${hostKey}` } })).status, 404, 'host token is not a stage token');
assert.equal((await fetch(`${origin}/api/rooms`, { method: 'POST', headers: { Origin: 'https://other.test' } })).status, 403, 'cross-origin creation rejected');
assert.equal((await fetch(`${origin}/api/rooms/${id}`, { method: 'PUT', headers: { Authorization: `Bearer ${hostKey}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ phase: 'running', arbitrary: 'code' }) })).status, 400, 'invalid state rejected');
console.log('Stage relay integration passed: create, host publish, reader fetch, token separation, missing credentials, cross-origin request, malformed state.');
